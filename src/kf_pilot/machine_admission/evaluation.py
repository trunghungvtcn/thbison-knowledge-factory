"""Automatically derived consistency labels, not expert gold or calibrated confidence."""
import argparse
import copy
from pathlib import Path

from .pipeline import code_hash, read_current
from .policy import POLICY_HASH, decide
from .storage import atomic
from kf_pilot.v166_evidence_completion.canonical import confined, digest, load


def evaluate(config_path, root):
    root = Path(root); result, draft = read_current(config_path, root)
    acq = load(root/'acquisition.json'); sources = {s['source_id']: s for s in acq['sources']}
    experiments = []
    for record in result['records']:
        if record['decision']['state'] != 'MACHINE_ACCEPTED':
            continue
        c = record['claim']; s = sources[c['evidence']['source_id']]; raw = confined(root, s['raw_path']).read_bytes()
        variants = [('exact_source_consistency', copy.deepcopy(c), True)]
        for field, value in [('quote', 'invented text'), ('start', c['evidence']['start']+1), ('raw_sha256', '0'*64), ('context', 'invented context')]:
            bad = copy.deepcopy(c); bad['evidence'][field] = value; variants.append(('mutated_evidence_'+field,bad,False))
        for field, value in [('manufacturer','THBISON'),('model','OTHER_MODEL'),('jurisdiction','VN')]:
            bad=copy.deepcopy(c); bad['scope'][field]=value; variants.append(('wrong_'+field,bad,False))
        bad=copy.deepcopy(c); bad['value']['value']='steel body'; variants.append(('wrong_value',bad,False))
        bad=copy.deepcopy(c); bad['as_of']='2026-09-05T00:00:00+07:00'; variants.append(('wrong_date',bad,False))
        bad=copy.deepcopy(c); bad['exception_ast']={'op':'UNRESOLVED','reason':'unknown'}; variants.append(('lost_exception',bad,False))
        bad=copy.deepcopy(c); bad['predicate']='inspection_interval'; variants.append(('r3_predicate',bad,False))
        for label, item, expected in variants:
            actual=decide(item,s,raw,result['corpus']['corpus_revision'],c['as_of'])['state']=='MACHINE_ACCEPTED'
            experiments.append({'origin_claim_hash':digest(c),'candidate_hash':digest(item),'kind':label,
                                'expected_accept':expected,'actual_accept':actual,'correct':actual==expected,
                                'source_sha256':s['raw_sha256'],'provenance_family':s['provenance_family']})
    positive=[e for e in experiments if e['expected_accept']]
    negatives=[e for e in experiments if not e['expected_accept']]
    evaluation={'status':'DATA_QUALITY_MEASURED','dataset_hash':digest(experiments),'policy_hash':POLICY_HASH,'code_hash':code_hash(),
                'label_origin':'AUTOGENERATED_PROVENANCE_TYPE_CONSISTENCY_NOT_EXPERT_GOLD',
                'cases':len(experiments),'positive_cases':len(positive),'negative_cases':len(negatives),
                'error_count':sum(not e['correct'] for e in experiments),'false_admissions':sum(e['actual_accept'] for e in negatives),
                'observed_consistency_precision':(sum(e['correct'] for e in positive)/len(positive)) if positive else None,
                'precision_sample_size':len(positive),'precision_error_count':sum(not e['correct'] for e in positive),
                'independent_families':len({e['provenance_family'] for e in experiments}),
                'precision_confidence_interval':None,'precision_interval_status':'NOT_VALID_CLUSTERED_WEAK_LABELS',
                'semantic_factual_precision':None,'semantic_factual_precision_status':'NOT_EVALUATED',
                'model_calls':None,'model_calls_status':'NOT_RUN','model_version':None,'prompt_hash':None,
                'tokens':None,'provider_cost':None,'provider_cost_status':'UNKNOWN',
                'training':'NOT_RUN','calibration':'NOT_CALIBRATED','train_dev_test_split':'NOT_RUN_ONE_FAMILY_ONLY',
                'ocr':'NOT_RUN','extended_automation':'NOT_CALIBRATED',
                'limitations':'Exact snippets and deliberate corruptions share source families. No statistical/general semantic/legal guarantee. No trained or LLM evaluator ran.',
                'experiments':experiments}
    return evaluation


def main():
    p=argparse.ArgumentParser(); p.add_argument('--config',required=True); p.add_argument('--root',required=True); p.add_argument('--output',required=True)
    a=p.parse_args(); value=evaluate(a.config,a.root); atomic(Path(a.output),value)
    print({k:v for k,v in value.items() if k not in {'experiments','limitations'}})


if __name__=='__main__':
    main()
